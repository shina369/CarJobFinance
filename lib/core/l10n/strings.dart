/// Extension on [AppLanguage] to translate keys.
extension AppLanguageStrings on AppLanguage {
  String tr(String key, {Map<String, String>? args}) {
    var value = Strings.t(key, tag);
    if (args != null) {
      args.forEach((k, v) {
        value = value.replaceAll('{$k}', v);
      });
    }
    return value;
  }
}

/// Top-level convenience that builds a [Locale] string for a tag.
String tagToDisplayLabel(String tag) {
  final lang = languageForTag(tag);
  return lang?.displayName ?? tag;
}
