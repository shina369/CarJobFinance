  /// Initialize intl date formatting for all supported locales.
  ///
  /// Must be called once at startup, before the first [DateFormat] is used
  /// with a non-default locale tag. Safe to call repeatedly.
  static Future<void> initIntlDateFormats() async {
    await Future.wait(
      SUPPORTED_LANGUAGES.map((l) => initializeDateFormatting(l.tag)),
    );
  }

  /// Resolve a string for the given language tag, falling back to pt_BR.
  static String t(String key, String localeTag) {
    final bundle = _bundlesByTag[localeTag] ?? _bundlesByTag['pt_BR']!;
    return bundle[key] ?? _bundlesByTag['pt_BR']![key] ?? key;
  }

  /// Merge two bundles: values from [override] win over [base].
  static Map<String, String> _merge(
      Map<String, String> base, Map<String, String> override) {
    final merged = Map<String, String>.from(base);
    merged.addAll(override);
    return merged;
  }

  /// Resolve a string for the given [AppLanguage].
  static String tFor(AppLanguage lang, String key) => t(key, lang.tag);

